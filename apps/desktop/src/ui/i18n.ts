export function translate(
  lang: Language,
  key: string,
  params: Record<string, string | number> = {},
) {
  const map = lang === 'en' ? en : zh;
  let text =
    renderMessages[lang][key] ??
    extraMessages[lang][key] ??
    map[(codes[key] ?? key) as Key] ??
    map.error;
  for (const [k, v] of Object.entries(params)) {
    text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}
const Context = createContext<{
  language: Language;
  setLanguage: (l: Language) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
} | null>(null);
export function LanguageProvider({
  children,
  onPreference,
}: {
  children: ReactNode;
  onPreference?: (l: Language) => void;
}) {
  const [language, setLanguage] = useState<Language>(() =>
    localStorage.getItem('building-language') === 'en' ? 'en' : 'zh-CN',
  );
  useEffect(() => {
    document.documentElement.lang = language;
    document.title = language === 'en' ? en.app : zh.app;
  }, [language]);
  return createElement(
    Context,
    {
      value: {
        language,
        setLanguage: (l) => {
          setLanguage(l);
          localStorage.setItem('building-language', l);
          onPreference?.(l);
        },
        t: (key, p) => translate(language, key, p),
      },
    },
    children,
  );
}
export function useLanguage() {
  const c = use(Context);
  if (!c) {
    throw new Error('LanguageProvider required');
  }
  return c;
}
